/** GENERATES `modules/shape/src/main/scala/okay/effects/shape/RecordWords.scala`: `record(f1, ..., fn)(make)(unmake)`,
 * a `Shape` of a
 * record of n fields, for arities 1 to 12 — Scala 2.13 has no abstraction over a tuple's arity, so the overloads are
 * written out, by this and not by hand. `sbt records` rewrites the file; it is committed, so the repository reads
 * plainly and an IDE sees it */
object Records {
  val arities: Range = 1 to 12

  def source: String = {
    val defs = arities.map(one)
    s"""package okay.effects.shape
       |
       |import okay.effects.algebra.FreeAp
       |
       |/** `record(f1, ..., fn)(make)(unmake)`: a `Shape` of a record of n fields — GENERATED by `sbt records`
       | * (project/Records.scala), arities ${arities.start} to ${arities.end} */
       |trait RecordWords {
       |${defs.mkString("\n")}
       |}
       |""".stripMargin
  }

  private def one(n: Int): String = {
    val as = (1 to n).map(i => s"A$i")
    val typeParams = (as :+ "P").mkString(", ")
    val params = (1 to n).map(i => s"f$i: Shape.Field[A$i]").mkString(", ")
    val (make, unmake, pure, write) =
      if (n == 1) ("make: A1 => P", "unmake: P => A1", "FreeAp.pure[Shape.Field, A1 => P](make)",
        "Vector(f1.name -> f1.shape.encode(unmake(p)))")
      else {
        val tuple = as.mkString("(", ", ", ")")
        val curried = (as :+ "P").mkString(" => ")
        val lambda =
          (1 to n).map(i => s"(a$i: A$i)").mkString(" => ") + " => make(" + (1 to n).map(i => s"a$i").mkString(
            ", ") + ")"
        val fields = (1 to n).map(i => s"f$i.name -> f$i.shape.encode(t._$i)").mkString(", ")
        (s"make: $tuple => P", s"unmake: P => $tuple", s"FreeAp.pure[Shape.Field, $curried]($lambda)",
          s"{ val t = unmake(p); Vector($fields) }")
      }
    val fields = (1 to n).foldLeft(pure)((acc, i) => s"FreeAp.Ap($acc, f$i.free)")
    s"""  def record[$typeParams]($params)($make)($unmake): Shape[P] =
       |    Shape.Record[P]($fields, (p: P) => $write)""".stripMargin
  }
}
